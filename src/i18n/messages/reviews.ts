export const reviewsMessages: Record<Locale, ReviewsMessages> = { en, fr, es, ar, ru };

/** "{n} reviews" with the singular form for 1. */
export function reviewsCountText(m: ReviewsMessages, n: number, fmt: (n: number) => string = String): string {
  return n === 1 ? m.reviewsCountOne : m.reviewsCount.replace("{n}", fmt(n));
}

export const fill = (s: string, vars: Record<string, string | number>) => s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
